import 'package:flutter/material.dart';

import '../../../core/theme/app_theme.dart';
import '../services/manual_exchange_service.dart';

class NigerianBankMark extends StatelessWidget {
  final ManualNigerianBankOption bank;
  final double size;

  const NigerianBankMark({super.key, required this.bank, this.size = 40});

  @override
  Widget build(BuildContext context) {
    final words = bank.name.split(RegExp(r'\s+'));
    final initials =
        words.take(2).map((word) => word.characters.first).join().toUpperCase();
    final fallback = Center(
      child: Text(initials,
          style: AppTextStyles.labelS.copyWith(color: AppColors.primary)),
    );
    final hasLogo = _logoCodes.contains(bank.code);
    return ExcludeSemantics(
      child: ClipRRect(
        borderRadius: BorderRadius.circular(size * .28),
        child: ColoredBox(
          color:
              hasLogo ? Colors.white : AppColors.primary.withValues(alpha: .10),
          child: SizedBox.square(
            dimension: size,
            child: hasLogo
                ? Image.asset(
                    'assets/images/nigerian_banks/${bank.code}.png',
                    fit: BoxFit.contain,
                    errorBuilder: (_, __, ___) => fallback,
                  )
                : fallback,
          ),
        ),
      ),
    );
  }
}

